#!/bin/zsh
# Fetch the Play upload keystore and write gitignored Gradle properties.
# Matches scripts/fastlane.sh: AWS profile a1, region us-east-1.
# Does not print secret values.
set -euo pipefail

script_dir=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
app_dir=$(CDPATH= cd -- "$script_dir/.." && pwd)

keystore_path="$app_dir/android/app/oslyn-upload.keystore"
props_path="$app_dir/android/keystore.properties"
aws_profile="a1"
aws_region="us-east-1"

if [[ ! -d "$app_dir/android/app" ]]; then
  echo "android/app is missing. From app/, run: npx expo prebuild --platform android" >&2
  exit 1
fi

tmp=$(mktemp -d)
cleanup() {
  rm -rf "$tmp"
}
trap cleanup EXIT

fetch_secret() {
  local secret_id="$1"
  local outfile="$2"
  if ! aws secretsmanager get-secret-value \
    --profile "$aws_profile" \
    --region "$aws_region" \
    --secret-id "$secret_id" \
    --query SecretString \
    --output text > "$outfile" || [[ ! -s "$outfile" ]]; then
    rm -f "$outfile"
    echo "Could not fetch ${secret_id}. Check AWS credentials (e.g. aws sso login / aws configure for profile ${aws_profile}, account 006033392195)." >&2
    exit 1
  fi
}

echo "Fetching oslynstudio/android-upload-keystore"
fetch_secret oslynstudio/android-upload-keystore "$tmp/keystore.b64"

echo "Fetching oslynstudio/android-upload-keystore-props"
fetch_secret oslynstudio/android-upload-keystore-props "$tmp/props.json"

python3 - "$tmp/keystore.b64" "$keystore_path" "$tmp/props.json" "$props_path" <<'PY'
import base64
import json
import pathlib
import sys

b64_path, keystore_path, props_json_path, props_out_path = sys.argv[1:5]

raw = pathlib.Path(b64_path).read_text().strip()
if raw.startswith('"') and raw.endswith('"'):
    raw = raw[1:-1]
raw = "".join(raw.split())
try:
    data = base64.b64decode(raw, validate=True)
except Exception:
    sys.stderr.write("oslynstudio/android-upload-keystore is not valid base64.\n")
    sys.exit(1)
if not data or data[0] != 0x30:
    sys.stderr.write("Decoded upload keystore is empty or not a PKCS12 file.\n")
    sys.exit(1)

keystore = pathlib.Path(keystore_path)
keystore.parent.mkdir(parents=True, exist_ok=True)
keystore.write_bytes(data)
keystore.chmod(0o600)

try:
    props = json.loads(pathlib.Path(props_json_path).read_text())
except Exception:
    sys.stderr.write("oslynstudio/android-upload-keystore-props is not JSON.\n")
    sys.exit(1)

required = ("storePassword", "keyPassword", "keyAlias")
missing = [key for key in required if not isinstance(props, dict) or not isinstance(props.get(key), str) or not props[key]]
if missing:
    sys.stderr.write(
        "oslynstudio/android-upload-keystore-props is missing: " + ", ".join(missing) + "\n"
    )
    sys.exit(1)
if props["keyAlias"] != "oslyn-upload":
    sys.stderr.write("oslynstudio/android-upload-keystore-props keyAlias is not oslyn-upload.\n")
    sys.exit(1)

def escape_property(value):
    return (
        value.replace("\\", "\\\\")
        .replace("\n", "\\n")
        .replace("\r", "\\r")
        .replace("\t", "\\t")
        .replace(" ", "\\ ")
        .replace("=", "\\=")
        .replace(":", "\\:")
        .replace("#", "\\#")
        .replace("!", "\\!")
    )

lines = [
    "# Generated by scripts/android-release-env.sh. Do not commit.",
    "OSLYN_UPLOAD_STORE_FILE=" + escape_property(str(keystore.resolve())),
    "OSLYN_UPLOAD_STORE_PASSWORD=" + escape_property(props["storePassword"]),
    "OSLYN_UPLOAD_KEY_ALIAS=" + escape_property(props["keyAlias"]),
    "OSLYN_UPLOAD_KEY_PASSWORD=" + escape_property(props["keyPassword"]),
    "",
]
out = pathlib.Path(props_out_path)
out.write_text("\n".join(lines))
out.chmod(0o600)
PY

chmod 600 "$keystore_path" "$props_path"
echo "Wrote android/app/oslyn-upload.keystore and android/keystore.properties"
